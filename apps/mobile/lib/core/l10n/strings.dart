/// Localised copy, keyed by locale tag.
///
/// A plain map rather than ARB + gen-l10n: the generator adds a build step and generated sources,
/// and the lookup API below is the same shape it produces, so moving to it later is a swap and
/// not a rewrite of every call site.
///
/// Locales match the backend exactly — `tkm`, not the ISO `tk`. The API's `@IsIn(["ru","en","tkm"])`
/// rejects `tk`, so the app must not "correct" it on the way out.
///
/// App copy is resolved through [StringsScope], not through `Localizations.localeOf`, because
/// `tkm` is not a locale `flutter_localizations` knows: asking `GlobalMaterialLocalizations` to
/// load it fails. Material's own widgets get [materialLocale] instead, which maps `tkm` onto `ru`.
class Strings {
  const Strings(this.locale);

  final String locale;

  /// What Material's built-in widgets (date pickers, "Cancel", scrollbar semantics) are shown in.
  /// There is no Turkmen Material translation, and Russian is the language Turkmen users here
  /// already read — better than falling back to English.
  Locale get materialLocale => Locale(locale == 'tkm' ? 'ru' : locale);

  /// Normalises anything — a device tag, a stored `user.locale` — onto a locale we actually have.
  factory Strings.resolve(String? tag) {
    final normalized = switch (tag) {
      'tk' || 'tkm' || 'tuk' => 'tkm',
      'en' => 'en',
      _ => 'ru',
    };
    return Strings(normalized);
  }

  static const supportedLocales = [Locale('ru'), Locale('en'), Locale('tkm')];

  static Strings of(BuildContext context) =>
      context.dependOnInheritedWidgetOfExactType<StringsScope>()?.strings ??
      const Strings('ru');

  /// Looks a key up, falling back to Russian and then to [fallback].
  ///
  /// [fallback] exists for values the backend can invent — an order status this build has never
  /// heard of should render as the server's own word, not as the literal string `status.foo`.
  String get(String key, {String? fallback}) =>
      _table[locale]?[key] ?? _table['ru']![key] ?? fallback ?? key;

  /// The keys one locale actually defines, before the Russian fallback hides a gap. Exists for
  /// the parity test — a key added to `ru` only would otherwise render Russian to an English
  /// speaker with nothing failing.
  static Set<String> keysFor(String locale) =>
      _table[locale]?.keys.toSet() ?? const {};

  /// Turns an [AppException] into something a person can act on.
  ///
  /// The backend's own message wins when there is one: it is already localised and specific
  /// ("Неверный код" beats "Something went wrong"). The generic fallbacks below only cover the
  /// cases where the server said nothing useful — transport failures and 5xx.
  String error(AppException e) {
    final server = e.serverMessage;
    // The API now reports field-level failures as the stable code VALIDATION_FAILED instead of a
    // raw English validator sentence, so this can be said in the user's language.
    if (e.serverCode == 'VALIDATION_FAILED') return get('err.validation');
    final coded = _errorCodeKeys[server];
    if (coded != null) return get(coded);
    // A code we have not translated yet. Showing it raw puts INVALID_CREDENTIALS in front of a
    // customer, which is worse than saying nothing specific — the generic text below at least
    // tells them what to do. Business messages the API writes as real sentences are unaffected:
    // they do not look like this.
    if (server != null && server.isNotEmpty && !_looksLikeCode(server)) return server;
    return switch (e.kind) {
      AppErrorKind.network => get('err.network'),
      AppErrorKind.timeout => get('err.timeout'),
      AppErrorKind.unauthorized => get('err.unauthorized'),
      AppErrorKind.forbidden => get('err.forbidden'),
      AppErrorKind.notFound => get('err.notFound'),
      AppErrorKind.rateLimited => get('err.rateLimited'),
      AppErrorKind.server => get('err.server'),
      AppErrorKind.conflict ||
      AppErrorKind.validation ||
      AppErrorKind.unknown => get('err.unknown'),
    };
  }

  /// Stable codes the API answers business failures with, and the string that says each one in
  /// the reader's language. A code carries no language, which is the whole point: the same
  /// failure used to arrive as the English sentence "Invalid credentials" and was shown verbatim
  /// on the login screen of a Russian app.
  static const Map<String, String> _errorCodeKeys = {
    'INVALID_CREDENTIALS': 'err.invalidCredentials',
    'ACCOUNT_BLOCKED': 'err.accountBlocked',
    'PHONE_ALREADY_REGISTERED': 'err.phoneTaken',
    'CURRENT_PASSWORD_INCORRECT': 'err.currentPasswordWrong',
    'SHORT_LINK_NOT_RESOLVED': 'err.shortLink',
  };

  /// Whether a server message is a code rather than a sentence meant to be read. Codes are
  /// SCREAMING_SNAKE and single-token; every human-readable message the API writes has spaces
  /// or lowercase letters in it, so nothing legitimate is caught here.
  static bool _looksLikeCode(String message) =>
      RegExp(r'^[A-Z][A-Z0-9]*(_[A-Z0-9]+)*$').hasMatch(message);

